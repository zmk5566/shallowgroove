import {chromium, expect} from '@playwright/test';
import {spawn} from 'node:child_process';
import {once} from 'node:events';
const root=new URL('../../hexblocks_connect/',import.meta.url).pathname;
const proc=spawn(root+'.venv/bin/python',[root+'connect.py','--sim','--port','8769'],{stdio:['ignore','ignore','pipe']});
let browser,serviceReady=false,serviceError='';
proc.stderr?.on('data',data=>{serviceError+=data;});
try {
 for(let i=0;i<80;i++){try{if((await fetch('http://127.0.0.1:8769/api/state')).ok){serviceReady=true;break;}}catch{}await new Promise(r=>setTimeout(r,100));}
 if(!serviceReady)throw Error(`Connect service did not start: ${serviceError}`);
 browser=await chromium.launch(process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE?{executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE}:{});
 const page=await browser.newPage({locale:'zh-CN',viewport:{width:1024,height:768}}),errors=[];
 page.on('pageerror',e=>errors.push(String(e)));
 await page.goto('http://127.0.0.1:8769/?locale=en');
 await expect(page.locator('#connections')).toHaveText('Connect devices');
 await expect(page.locator('html')).toHaveAttribute('lang','en');
 await expect(page.locator('#topology .topo-node')).toHaveCount(3);
 await page.locator('.module-entry').last().click();
 const selected=await page.locator('#data-module').inputValue();
 await page.locator('#zoom-in').click();
 const zoom=await page.locator('#topology').getAttribute('viewBox');
 await page.locator('#pause-charts').click();
 const value=await page.locator('.chart output').textContent();
 await page.locator('#sim').fill('0.9');
 await page.locator('#language').selectOption('zh-CN');
 await expect(page.locator('#connections')).toHaveText('连接设备');
 await expect(page.locator('#pause-charts')).toHaveText('恢复图表');
 await expect(page.locator('.chart output')).toHaveText(value);
 await expect(page.locator('#data-module')).toHaveValue(selected);
 await expect(page.locator('#topology')).toHaveAttribute('viewBox',zoom);
 await expect(page.locator('#topology-status')).toContainText('个模块');
 await page.reload();
 await expect(page.locator('#connections')).toHaveText('连接设备');
 await page.goto('http://127.0.0.1:8769/?locale=en');
 await expect(page.locator('#connections')).toHaveText('Connect devices');
 await page.locator('#connections').click();
 await expect(page.locator('#pairing-hint')).toHaveText('Connect locally without pairing.');
 await page.locator('#server').fill('ws://192.168.1.2:5198/hexblocks/ws');
 await expect(page.locator('#pairing-hint')).toContainText('token');
 await page.locator('#disconnect').click();
 await expect(page.locator('#topology-status')).toHaveText('Connect a Hub to view topology');
 await page.locator('[data-close="connection-dialog"]').click();
 if(!await page.evaluate(()=>document.documentElement.scrollWidth===innerWidth))throw Error('Horizontal overflow');
 await page.goto('http://127.0.0.1:8769/?locale=invalid');
 await expect(page.locator('html')).toHaveAttribute('lang','en');
 const isolated=await browser.newContext({locale:'de-DE'});
 await isolated.addInitScript(()=>{Object.defineProperty(window,'localStorage',{get(){throw new Error('Storage blocked');}});});
 const fresh=await isolated.newPage();await fresh.goto('http://127.0.0.1:8769/');
 await expect(fresh.locator('#connections')).toHaveText('Connect devices');
 await fresh.locator('#language').selectOption('zh-CN');await expect(fresh.locator('#connections')).toHaveText('连接设备');
 if(errors.length)throw Error(errors.join('\n'));
 console.log('PASS Connect language, persistence, paused charts, selection, zoom, offline UI and storage fallback');
} finally {await browser?.close();proc.kill('SIGTERM');if(proc.exitCode===null)await once(proc,'exit');}
